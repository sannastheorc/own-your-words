# SEEDSED — build_commonwords.py
# Purpose: generate app/js/commonwords.js from NGSL 1.2 and NGSL-Spoken 1.2 (CC BY-SA 4.0), so a
#          made-up misspelling is never accidentally a real word.
# Boundaries: build-time only. Usage: python3 -I scripts/build_commonwords.py build/ngsl_stats.csv build/ngsl_spoken_stats.csv app/js/commonwords.js
import csv
import re
import sys

words = set()
for path in sys.argv[1:3]:
    with open(path, encoding="utf-8") as f:
        for row in list(csv.reader(f))[1:]:
            w = row[0].strip().lower()
            if re.fullmatch(r"[a-z]+", w):
                words.add(w)
with open(sys.argv[3], "w", encoding="utf-8") as f:
    f.write("// SEEDSED — commonwords.js (GENERATED by scripts/build_commonwords.py)\n"
            "// Purpose: common real words (NGSL 1.2 and NGSL-Spoken 1.2, Browne, Culligan & Phillips, CC BY-SA 4.0),\n"
            "// so a made-up misspelling is never accidentally a real word.\n"
            'export const COMMON_WORDS = new Set("' + " ".join(sorted(words)) + '".split(" "));\n')
print(len(words))
